from dataclasses import dataclass

# Text banks for the chat_threads generator. Messages are assembled word by word from
# templates rather than sampled from a fixed sentence pool: the grammatical skeleton
# repeats the way real prose does, while content words vary combinatorially. A fixed
# sentence pool compresses several times better than English and would turn the suite
# into a measurement of the generator instead of the engine.


@dataclass(frozen=True)
class Topic:
    name: str
    terms: tuple[str, ...]
    tools: tuple[str, ...]
    metrics: tuple[str, ...]


