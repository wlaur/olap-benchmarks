import { writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

import duckdb from "duckdb"

const RESULTS_DB_PATH = fileURLToPath(new URL("../public/data/results.db", import.meta.url))
const OUTPUT_PATH = new URL("../src/lib/generated/db.ts", import.meta.url)

const TIMESTAMP_TYPE = "ColumnType<Date, Date | string, Date | string>"

const SCALAR_TYPES = {
  BIGINT: "number",
  BOOLEAN: "boolean",
  DOUBLE: "number",
  FLOAT: "number",
  INTEGER: "number",
  SMALLINT: "number",
  VARCHAR: "string",
}

function columnTsType(column) {
  let tsType
  if (column.data_type === "JSON") {
    tsType = "Json"
  } else if (column.data_type.startsWith("TIMESTAMP")) {
    tsType = TIMESTAMP_TYPE
  } else {
    tsType = SCALAR_TYPES[column.data_type]
  }

  if (tsType === undefined) {
    throw new Error(`No TypeScript mapping for DuckDB type ${column.data_type}`)
  }

  if (column.column_default?.startsWith("nextval")) {
    return `Generated<${tsType}>`
  }

  return column.is_nullable === "YES" ? `${tsType} | null` : tsType
}

function pascalCase(tableName) {
  return tableName
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("")
}

const db = new duckdb.Database(RESULTS_DB_PATH, { access_mode: "READ_ONLY" })

const columns = await new Promise((resolve, reject) => {
  db.all(
    `select table_name, column_name, data_type, is_nullable, column_default
     from information_schema.columns
     where table_schema = 'main'
     order by table_name, ordinal_position`,
    (err, rows) => (err ? reject(err) : resolve(rows)),
  )
})

db.close()

const tables = new Map()
for (const column of columns) {
  const tableColumns = tables.get(column.table_name) ?? []
  tableColumns.push(column)
  tables.set(column.table_name, tableColumns)
}

const tableNames = [...tables.keys()].sort()
const hasJson = columns.some((column) => column.data_type === "JSON")

const parts = [
  "/** generated by scripts/generate-db-types.mjs */",
  `import {
  type Selectable,
  type Insertable,
  type Updateable,
  type Generated,
  type ColumnType,
} from "kysely"`,
]

if (hasJson) {
  parts.push(
    "type Json = ColumnType<JsonValue, string, string>",
    "type JsonValue = JsonArray | JsonObject | boolean | null | number | string",
    "type JsonArray = JsonValue[]",
    "type JsonObject = { [key in string]?: JsonValue | undefined }",
  )
}

for (const tableName of tableNames) {
  const typeName = pascalCase(tableName)
  const fields = tables
    .get(tableName)
    .map((column) => `  ${column.column_name}: ${columnTsType(column)}`)
    .join("\n")

  parts.push(
    `export type ${typeName} = {\n${fields}\n}`,
    `export type ${typeName}Insertable = Insertable<${typeName}>`,
    `export type ${typeName}Selectable = Selectable<${typeName}>`,
    `export type ${typeName}Updateable = Updateable<${typeName}>`,
  )
}

parts.push(
  `export interface DB {\n${tableNames.map((name) => `  ${name}: ${pascalCase(name)}`).join("\n")}\n}`,
)

await writeFile(OUTPUT_PATH, `${parts.join("\n\n")}\n`)
console.log(`Generated ${fileURLToPath(OUTPUT_PATH)} (${tableNames.length} tables)`)
